"""Command line: `ilcd <command>`. Module commands are added here as modules are implemented.

ilcd info                       version, data root, config directory
ilcd contracts list             every contract with owner and status
ilcd contracts show <name>      one contract's fields
ilcd contracts check <name> <path>   validate a file
ilcd contracts docs             Markdown reference of all contracts (docs/contracts.md)
ilcd config check               validate every region, site and delivery override
"""

import argparse
import json
import sys

import ilcd

from .common import config, contracts, io, paths


def _info(args):
    print(f"ilcd {ilcd.__version__}")
    for name, fn in (("data root", paths.data_root), ("config dir", paths.config_dir)):
        try:
            print(f"{name}: {fn()}")
        except paths.ConfigurationError as e:
            print(f"{name}: not set ({e})")
    print(f"contracts: {len(contracts.all_contracts())}")


def _list(args):
    for c in sorted(contracts.all_contracts().values(), key=lambda c: (c.owner, c.name)):
        print(f"{c.tag:24s} {c.kind:8s} {c.owner:12s} {c.status:6s} {c.path[0]}")


def _show(args):
    c = contracts.get(args.name)
    print(render(c))


def _check(args):
    c = contracts.get(args.name)
    if c.kind in ("table", "vector"):
        t = io.read_table(args.path, c)
        print(f"ok: {c.tag}, {t.num_rows} rows")
    elif c.kind == "raster":
        c.check_raster(args.path)
        print(f"ok: {c.tag}")
    else:
        io.read_json(args.path, c)
        print(f"ok: {c.tag}")


def render(c: contracts.Contract) -> str:
    """Markdown section of one contract."""
    lines = [f"### `{c.tag}` ({c.kind}, owner {c.owner}, {c.status})", "", c.description, ""]
    lines.append("Path: " + ", ".join(f"`{p}`" for p in c.path) + "  ")
    if c.key:
        lines.append("Key: " + ", ".join(f"`{k}`" for k in c.key) + "  ")
    if c.geometry:
        lines.append(f"Geometry: {c.geometry['type']} in {c.geometry['crs']}  ")
    lines.append("")
    if c.columns:
        lines += ["| column | type | unit | null | description |", "|---|---|---|---|---|"]
        for col in c.columns:
            desc = col.description + (f" One of: {', '.join(col.enum)}." if col.enum else "")
            lines.append(
                f"| `{col.name}` | {col.type} | {col.unit or ''} | {'yes' if col.nullable else ''} | {desc.strip()} |"
            )
    if c.bands:
        r = c.raster
        lines += [
            f"Raster: {r['crs']}, {r['resolution_m']} m, {r.get('width', '?')} x {r.get('height', '?')} px",
            "",
            "| band | dtype | description |",
            "|---|---|---|",
        ]
        lines += [f"| `{b['name']}` | {b['dtype']} | {b.get('description', '')} |" for b in c.bands]
    if c.schema:
        lines += ["```json", json.dumps(c.schema, indent=1), "```"]
    return "\n".join(lines) + "\n"


def docs() -> str:
    """docs/contracts.md, generated; tests check it is up to date."""
    out = [
        "# Contracts",
        "",
        "Generated by `ilcd contracts docs` from `src/ilcd/schemas/`; do not edit by hand. "
        "Paths are relative to `$ILCD_DATA_ROOT` (config files: to the repository).",
        "",
    ]
    by_owner = {}
    for c in contracts.all_contracts().values():
        by_owner.setdefault(c.owner, []).append(c)
    order = ["data_src", "flightlines", "refs", "align", "eval", "change", "viz_label", "config", "common"]
    for owner in sorted(by_owner, key=lambda o: order.index(o) if o in order else 99):
        out += [f"## {owner}", ""]
        out += [render(c) for c in sorted(by_owner[owner], key=lambda c: c.tag)]
    return "\n".join(out)


def _docs(args):
    sys.stdout.write(docs())


def _config_check(args):
    problems = 0
    for name in config.region_names():
        try:
            r = config.load_region(name)
            print(f"region {name}: ok ({next(iter(r.footprint.items()))})")
        except Exception as e:  # report every problem, not just the first
            problems += 1
            print(f"region {name}: {e}")
    for name in config.site_names():
        try:
            config.load_site(name)
            print(f"site {name}: ok")
        except Exception as e:
            problems += 1
            print(f"site {name}: {e}")
    try:
        print(f"deliveries.yaml: ok ({len(config.load_delivery_overrides())} entries)")
    except Exception as e:
        problems += 1
        print(f"deliveries.yaml: {e}")
    return 1 if problems else 0


def main(argv=None):
    ap = argparse.ArgumentParser(prog="ilcd", description=ilcd.__doc__)
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("info").set_defaults(fn=_info)
    c = sub.add_parser("contracts").add_subparsers(dest="sub", required=True)
    c.add_parser("list").set_defaults(fn=_list)
    s = c.add_parser("show")
    s.add_argument("name")
    s.set_defaults(fn=_show)
    k = c.add_parser("check")
    k.add_argument("name")
    k.add_argument("path")
    k.set_defaults(fn=_check)
    c.add_parser("docs").set_defaults(fn=_docs)
    g = sub.add_parser("config").add_subparsers(dest="sub", required=True)
    g.add_parser("check").set_defaults(fn=_config_check)
    from .data_src import cli as data_src_cli

    data_src_cli.register(sub)
    from .flightlines import cli as flightlines_cli

    flightlines_cli.register(sub)
    from .refs import cli as refs_cli

    refs_cli.register(sub)
    from .align import cli as align_cli

    align_cli.register(sub)
    from .eval import cli as eval_cli

    eval_cli.register(sub)
    args = ap.parse_args(argv)
    return args.fn(args) or 0


if __name__ == "__main__":
    sys.exit(main())
